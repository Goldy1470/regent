export function sfrrFixTemplate(product: string) {
  const fixes = [
    "Publish a 'what you get' carousel: exact shade/swatch under natural light + under TikTok lighting to kill shade-mismatch returns.",
    "Move claims from outcome to appearance: fade 'anti-aging' language, lead with finish and feel.",
    "Add dimension/quantity callouts to the first gallery image.",
    "Bump fragiles into rigid mailers and add a 'sealed check' unboxing cue video your affiliates can stitch.",
    "Pin a top-comment FAQ about sizing and storage on the video your top affiliate posted.",
  ];
  return fixes[Math.abs(hash(product)) % fixes.length];
}

export function emphasisNote(score: number, amount: number) {
  if (score >= 85) {
    return `Evidence strength: abusers embedded in multiple signals. Track this packet for a ${money(amount)} recovery and blacklist the buyer fingerprint.`;
  }
  if (score >= 60) {
    return `Evidence strength: solid. File within 24h — evidence windows close fast on this claim type.`;
  }
  return `Evidence strength: soft. Route to goodwill refund or fix the listing — don't burn a dispute on a weak packet.`;
}

function hash(s: string) {
  let h = 0;
  for (let i = 0; i < s.length; i++) {
    h = (h << 5) - h + s.charCodeAt(i);
    h |= 0;
  }
  return h;
}
